"""Profile the NSSE synthetic data with aggregates only and write docs/DATA_SCHEMA.md.

Prints no rows. For each column: type, distinct values, null share and a proposed privacy role.
Value counts are shown only for quasi-identifiers with fewer than 30 distinct values, and any
count below 5 is shown as "<5".

Run from /backend:  python scripts/profile_data.py
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "NSSE-synthetic.csv"
OUT = ROOT / "docs" / "DATA_SCHEMA.md"
NA = ["#NULL!", " ", "-9"]

DIRECT = {"ID"}
QUASI = {
    "Year", "Class", "program", "First Time First Year", "affiliation",
    "MAJnum", "MAJfirst", "MAJsecond", "MAJfirstcode", "MAJsecondcode", "MAJfirstcol", "MAJsecondcol",
    "begincol", "attend_voc", "attend_com", "attend_col", "attend_none", "attend_other", "edaspire", "logdate",
}
SCORED = {"Class", "affiliation", "MAJfirst", "MAJsecond", "MAJnum", "begincol"}  # used by risk.py today
OTHER = {"duration"}


def role(col: str) -> str:
    if col in DIRECT:
        return "direct identifier"
    if col in QUASI:
        return "quasi-identifier" + (" (scored)" if col in SCORED else "")
    if col in OTHER:
        return "other (survey metadata)"
    return "sensitive attribute (survey response)"


def counts(series: pd.Series) -> str:
    vc = series.value_counts(dropna=False)
    parts = [f"{'(missing)' if pd.isna(v) else v}: {'<5' if n < 5 else n}" for v, n in vc.items()]
    return "; ".join(parts)


def main() -> None:
    df = pd.read_csv(DATA, na_values=NA, low_memory=False)
    lines = [
        "# NSSE synthetic data: schema and privacy roles",
        "",
        f"Source: organizers' `NSSE-synthetic.csv` (kept in `data/`, never committed). "
        f"{len(df):,} rows, {df.shape[1]} columns. Generated by `backend/scripts/profile_data.py` "
        "from aggregates only; no rows are shown and counts below 5 are written as \"<5\".",
        "",
        "Roles: **direct identifier** names one record by itself; **quasi-identifier** is ordinary on its own "
        "but identifying in combination; **sensitive attribute** is what must not be linked back to a person. "
        "\"(scored)\" marks the quasi-identifiers the risk engine uses today.",
        "",
        "| Column | Type | Distinct | Null share | Proposed role |",
        "|---|---|---|---|---|",
    ]
    for col in df.columns:
        s = df[col]
        lines.append(f"| `{col}` | {s.dtype} | {s.nunique(dropna=True):,} | {s.isna().mean():.1%} | {role(col)} |")

    lines += ["", "## Value counts for quasi-identifiers with fewer than 30 values", ""]
    for col in df.columns:
        if col in QUASI and df[col].nunique(dropna=True) < 30:
            lines.append(f"- **`{col}`**: {counts(df[col])}")

    lines += ["", "## Quasi-identifiers with 30 or more values", ""]
    for col in df.columns:
        if col in QUASI and df[col].nunique(dropna=True) >= 30:
            lines.append(f"- **`{col}`**: {df[col].nunique(dropna=True):,} distinct values (not listed)")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    roles = pd.Series([role(c).split(" (")[0] for c in df.columns]).value_counts()
    print(f"wrote {OUT}: {len(df):,} rows, {df.shape[1]} columns; roles: {roles.to_dict()}")


if __name__ == "__main__":
    main()

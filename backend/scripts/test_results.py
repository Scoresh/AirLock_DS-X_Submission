"""Write docs/TEST_RESULTS.md: detection on planted identifiers, participants, format rules, round trip, tests.

Everything is computed from the sample documents we wrote (fictional people) and the Faker fixture;
no real rows are written. Run from /backend:  python scripts/test_results.py
"""
import io
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import pandas as pd  # noqa: E402

from app import csv_mode, format_rules, risk, scrub  # noqa: E402
from app.parse import parse_pdf  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SAMPLES = ROOT / "samples"

PLANTED_IDS = {
    "demo-thesis.pdf": {
        "PERSON": ["Jordan Whitfield", "Elena Marchetti", "Samuel Okafor", "Priya Raman", "Maya Lindqvist"],
        "EMAIL": ["jwhitfield@bu.edu", "mlindq@bu.edu"], "PHONE": ["617-555-0142"],
        "STUDENT_ID": ["U48213907"], "SECTION": ["04"],
    },
    "test-thesis.pdf": {"PERSON": ["Maya Lindqvist"], "EMAIL": ["mlindq@bu.edu"], "PHONE": ["617-555-0142"]},
}
PLANTED_PARTICIPANTS = {"demo-thesis.pdf": {"PARTICIPANT_02": 3, "PARTICIPANT_03": 5, "PARTICIPANT_04": 4,
                                            "PARTICIPANT_05": 3, "PARTICIPANT_07": 3, "PARTICIPANT_09": 4}}
EXPECTED_K = {"PARTICIPANT_02": 9, "PARTICIPANT_03": 1, "PARTICIPANT_04": 1, "PARTICIPANT_05": 331,
              "PARTICIPANT_07": 1, "PARTICIPANT_09": 1}


def identifier_rows() -> list[str]:
    rows = []
    for name, planted in PLANTED_IDS.items():
        parsed = parse_pdf((SAMPLES / name).read_bytes(), f"results-{name}")
        scrubbed = scrub.scrub(parsed)
        key = scrub.load_key(parsed.doc_id)
        text = "\n".join(p.text for p in scrubbed.scrubbed_pages).lower()
        found_values = set(key.values())
        for kind, values in planted.items():
            hit = [v for v in values if v in found_values]
            leaked = [v for v in values if v.lower() in text and not re.fullmatch(r"\d+", v)]
            rows.append(f"| {name} | {kind} | {len(values)} | {len(hit)} | {len(leaked)} |")
        extra = found_values - {v for vs in planted.values() for v in vs}
        rows.append(f"| {name} | false positives | - | {len(extra)} | - |")
        (scrub.KEYS_DIR / f"{parsed.doc_id}.json").unlink(missing_ok=True)
    return rows


def participant_rows() -> list[str]:
    rows = []
    parsed = parse_pdf((SAMPLES / "demo-thesis.pdf").read_bytes(), "results-participants")
    scrubbed = scrub.scrub(parsed)
    found = {p.id: p for p in scrubbed.participants}
    scored = {p.id: p for p in risk.score(scrubbed, []).participants}
    for pid, n_attrs in PLANTED_PARTICIPANTS["demo-thesis.pdf"].items():
        got = len(found[pid].attributes) if pid in found else 0
        k = scored[pid].k if pid in scored else None
        ok = "yes" if got >= n_attrs and k == EXPECTED_K[pid] else "no"
        rows.append(f"| {pid} | {n_attrs} | {got} | {EXPECTED_K[pid]} | {k} | {ok} |")
    (scrub.KEYS_DIR / f"{parsed.doc_id}.json").unlink(missing_ok=True)
    return rows


def format_line() -> str:
    rows = format_rules.checklist(parse_pdf((SAMPLES / "demo-thesis.pdf").read_bytes(), "results-format"))
    failed = sum(not r["passed"] for r in rows)
    return f"{len(rows)} rules ran; {failed} flagged the planted errors (details in `docs/VALIDATION.md`)."


def round_trip_line() -> str:
    fixture = ROOT / "tests" / "fixtures" / "nsse_fixture.csv"
    original = pd.read_csv(fixture, dtype=str, keep_default_na=False)
    scrubbed, _ = csv_mode.scrub_table(fixture.read_bytes(), "results-roundtrip")
    restored = csv_mode.restore_table(scrubbed, csv_mode.load_key("results-roundtrip"))
    (scrub.KEYS_DIR / "csv-results-roundtrip.json").unlink(missing_ok=True)
    same = restored.equals(original)
    leaked = int(scrubbed["ID"].isin(set(original["ID"])).sum())
    return (f"Faker fixture, {len(original)} rows: restored table identical to the original: **{'yes' if same else 'no'}**; "
            f"original IDs left in the scrubbed table: **{leaked}**.")


def pytest_line() -> str:
    out = subprocess.run([sys.executable, "-m", "pytest", "-q"], cwd=ROOT, capture_output=True, text=True)
    return out.stdout.strip().splitlines()[-1] if out.stdout else "pytest did not run"


def main() -> None:
    lines = ["# Test results", "",
             "Generated by `backend/scripts/test_results.py`. The documents are ones we wrote with fictional "
             "people; tests use a Faker fixture. Participant k-values come from the organizers' NSSE synthetic data.", "",
             "## Direct identifiers planted in the sample PDFs", "",
             "| Document | Type | Planted | Replaced with a token | Still visible in scrubbed text |", "|---|---|---|---|---|"]
    lines += identifier_rows()
    lines += ["", "\"False positives\" counts values tokenized that were not planted (for example a citation author).", "",
              "## Participants described in the demo thesis", "",
              "| Participant | Details planted | Details recognised | Expected k | Computed k | Correct |", "|---|---|---|---|---|---|"]
    lines += participant_rows()
    lines += ["", "## Format rules", "", format_line(), "",
              "## CSV token round trip", "", round_trip_line(), "",
              "## Automated tests", "", f"`pytest`: {pytest_line()} (k-values on planted fixture groups, thresholds, "
              "gate, leak tests on the model request, token restore, CSV mode, format rules).", ""]
    (ROOT / "docs" / "TEST_RESULTS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
